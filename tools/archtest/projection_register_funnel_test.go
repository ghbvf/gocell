const (
	// Derived from PlatformModulePath (ARCHTEST-MODULE-PATH-FUNNEL-01: no bare
	// module-path literal — the sibling apply-hook const is grandfathered in the
	// frozen baseline; new ones must derive).
	projectionRegistrarPkgPath = PlatformFrameworkModulePath + "/kernel/cell"
	projectionRegisterMethod   = "RegisterProjection"
)

// projectionCellgenMarkerLine is the DO NOT EDIT marker emitted by
// gocell generate cell into cell_gen.go / healthz_gen.go / slice_gen.go.
const projectionCellgenMarkerLine = "// Code generated by gocell generate cell. DO NOT EDIT."

// projectionFileHasCellgenMarker reports whether the file at absPath contains
// the cellgen DO NOT EDIT marker line.
func projectionFileHasCellgenMarker(absPath string) bool {
	f, err := os.Open(absPath) //nolint:gosec // archtest-internal module-root relative path
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		if strings.TrimSpace(scanner.Text()) == projectionCellgenMarkerLine {
			return true
		}
	}
	return false
}

// isProjectionRegisterCall reports whether call is a method call to
// cell.Registrar.RegisterProjection (or *RegistryRecorder.RegisterProjection),
// resolved via *types.Info.
func isProjectionRegisterCall(call *ast.CallExpr, info *types.Info) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != projectionRegisterMethod {
		return false
	}
	fn, ok := ResolveMethodCall(info, sel)
	if !ok || fn == nil {
		return false
	}
	if fn.Pkg() == nil || fn.Pkg().Path() != projectionRegistrarPkgPath {
		return false
	}
	if fn.Name() != projectionRegisterMethod {
		return false
	}
	sig, ok := fn.Type().(*types.Signature)
	if !ok {
		return false
	}
	recv := sig.Recv()
	if recv == nil {
		return false
	}
	recvT := recv.Type()
	if ptr, ok := recvT.(*types.Pointer); ok {
		recvT = ptr.Elem()
	}
	// Interface method (Registrar) carries an *types.Interface receiver type via a
	// *types.Named; concrete (*RegistryRecorder) carries a *types.Named directly.
	named, ok := recvT.(*types.Named)
	if !ok {
		return false
	}
	if named.Obj().Pkg() == nil || named.Obj().Pkg().Path() != projectionRegistrarPkgPath {
		return false
	}
	switch named.Obj().Name() {
	case "Registrar", "RegistryRecorder":
		return true
	default:
		return false
	}
}

// isProjectionRegisterAllowed reports whether the file at the given rel/abs path
// may call reg.RegisterProjection:
//   - _test.go files (seam tests / test cells)
//   - the cellgen wiring file cell_gen.go ONLY, bearing the DO-NOT-EDIT marker.
//
// The marker alone is insufficient: the banner also appears in healthz_gen.go /
// slice_gen.go, so the allowlist requires basename == "cell_gen.go" AND the
// marker (basename pins the producer, marker pins it as generated).
func isProjectionRegisterAllowed(rel, absPath string) bool {
	if strings.HasSuffix(rel, "_test.go") {
		return true
	}
	if filepath.Base(rel) == "cell_gen.go" && projectionFileHasCellgenMarker(absPath) {
		return true
	}
	return false
}

// TestProjectionRegisterFunnel01 enforces PROJECTION-REGISTER-FUNNEL-01:
// reg.RegisterProjection must only be called from _test.go files or the cellgen
// DO-NOT-EDIT cell_gen.go. Any other production callsite is a violation.
//
// PR-04b status: load-bearing active guard. The first production callsite exists —
// examples/todoorder/cells/ordercell/cell_gen.go (orderprojection harness, #834) —
// and the allowlist confines that and every future call to cell_gen.go + _test.go.
func TestProjectionRegisterFunnel01(t *testing.T) {
	t.Parallel()
	if testing.Short() {
		t.Skip("skipping packages.Load-based archtest in -short mode")
	}

	root := findModuleRoot(t)
	allPatterns := prodscan.Patterns(root)

	var diags []Diagnostic

	_ = Run(t, Typed(TypedOpts{Tests: false, Tags: FlatNonDefaultTags()}, allPatterns),
		func(p *Pass) []Diagnostic {
			if p.Pkg == nil || p.TypesInfo == nil {
				return nil
			}
			for _, f := range p.Files {
				rel := p.Rel(f)
				absPath := p.Abs(f)
				if isProjectionRegisterAllowed(rel, absPath) {
					continue
				}
				EachInSubtree[ast.CallExpr](f, func(call *ast.CallExpr) {
					if !isProjectionRegisterCall(call, p.TypesInfo) {
						return
					}
					diags = append(diags, Diagnostic{
						Rel:  rel,
						Line: p.Fset.Position(call.Pos()).Line,
						Message: fmt.Sprintf(
							"PROJECTION-REGISTER-FUNNEL-01: reg.RegisterProjection called from "+
								"non-allowlisted file %s (line %d). Only _test.go files and the "+
								"cellgen DO-NOT-EDIT cell_gen.go may call RegisterProjection. cellgen "+
								"derives these from slice.yaml contractUsages — hand-writing them "+
								"bypasses the single source of truth.",
							rel, p.Fset.Position(call.Pos()).Line,
						),
					})
				})
			}
			return nil
		})

	sort.Slice(diags, func(i, j int) bool {
		if diags[i].Rel != diags[j].Rel {
			return diags[i].Rel < diags[j].Rel
		}
		return diags[i].Line < diags[j].Line
	})
	Report(t, "PROJECTION-REGISTER-FUNNEL-01", diags)
}

// TestProjectionRegisterFunnel01_ReverseFixture loads the synthetic violation
// fixture and asserts: cell_gen.go (banner) is ALLOWED (no diagnostic); a
// RegisterProjection call in healthz_gen.go (banner, wrong basename) and in a
// non-generated rogue file BOTH fire.
func TestProjectionRegisterFunnel01_ReverseFixture(t *testing.T) {
	t.Parallel()
	if testing.Short() {
		t.Skip("skipping packages.Load-based archtest in -short mode")
	}

	root := findModuleRoot(t)
	fixtureDir := filepath.Join(root, "tools", "archtest", "testdata", "projection_register_violate")

	var diags []Diagnostic

	_ = Run(t, StandaloneModule(fixtureDir, TypedOpts{Tests: false}, []string{"./..."}),
		func(p *Pass) []Diagnostic {
			if p.Pkg == nil || p.TypesInfo == nil {
				return nil
			}
			for _, f := range p.Files {
				rel := p.Rel(f)
				absPath := p.Abs(f)
				if isProjectionRegisterAllowed(rel, absPath) {
					continue
				}
				EachInSubtree[ast.CallExpr](f, func(call *ast.CallExpr) {
					if !isProjectionRegisterCall(call, p.TypesInfo) {
						return
					}
					diags = append(diags, Diagnostic{
						Rel:  rel,
						Line: p.Fset.Position(call.Pos()).Line,
					})
				})
			}
			return nil
		})

	var firedHealthz, firedCellGen, firedRogue bool
	for _, d := range diags {
		switch filepath.Base(d.Rel) {
		case "healthz_gen.go":
			firedHealthz = true
		case "cell_gen.go":
			firedCellGen = true
		case "rogue_callsite.go":
			firedRogue = true
		}
	}
	assert.False(t, firedCellGen,
		"reg.RegisterProjection in the sanctioned cell_gen.go (banner) must be allowed")
	assert.True(t, firedHealthz,
		"reg.RegisterProjection in healthz_gen.go (banner, wrong basename) MUST fire")
	assert.True(t, firedRogue,
		"reg.RegisterProjection in a non-generated business file MUST fire")
}

// TestProjectionRegisterFunnel01_ReverseBlindSpot_NoFuncValue (blind spot B1)
// asserts no production non-test file holds a reg.RegisterProjection function
// value (method expression assigned to a variable, not called).
func TestProjectionRegisterFunnel01_ReverseBlindSpot_NoFuncValue(t *testing.T) {
	t.Parallel()
	if testing.Short() {
		t.Skip("skipping archtest in -short mode")
	}

	root := findModuleRoot(t)
	allPatterns := prodscan.Patterns(root)

	var violations []string

	_ = Run(t, Typed(TypedOpts{Tests: false, Tags: FlatNonDefaultTags()}, allPatterns),
		func(p *Pass) []Diagnostic {
			if p.Pkg == nil || p.TypesInfo == nil {
				return nil
			}
			calleePos := make(map[interface{}]struct{})
			for _, f := range p.Files {
				EachInSubtree[ast.CallExpr](f, func(call *ast.CallExpr) {
					sel, ok := call.Fun.(*ast.SelectorExpr)
					if !ok || sel.Sel.Name != projectionRegisterMethod {
						return
					}
					if isProjectionRegisterCall(call, p.TypesInfo) {
						calleePos[sel.Sel] = struct{}{}
					}
				})
			}

			for _, f := range p.Files {
				rel := p.Rel(f)
				if strings.HasSuffix(rel, "_test.go") {
					continue
				}
				EachInSubtree[ast.SelectorExpr](f, func(sel *ast.SelectorExpr) {
					if sel.Sel.Name != projectionRegisterMethod {
						return
					}
					if _, isCallee := calleePos[sel.Sel]; isCallee {
						return
					}
					fn, ok := ResolveMethodCall(p.TypesInfo, sel)
					if !ok || fn == nil {
						return
					}
					if fn.Pkg() == nil || fn.Pkg().Path() != projectionRegistrarPkgPath {
						return
					}
					violations = append(violations, fmt.Sprintf(
						"%s:%d: reg.RegisterProjection used as a function value (not a direct call) "+
							"— would escape PROJECTION-REGISTER-FUNNEL-01 detection (blind spot B1)",
						rel, p.Fset.Position(sel.Sel.Pos()).Line,
					))
				})
			}
			return nil
		})

	assert.Empty(t, violations,
		"blind spot B1: no production non-test file should hold a reg.RegisterProjection function value")
}
