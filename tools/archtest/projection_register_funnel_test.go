// INVARIANT: PROJECTION-REGISTER-FUNNEL-01
//
// PROJECTION-REGISTER-FUNNEL-01 — cell.Registrar.RegisterProjection caller allowlist.
//
// reg.RegisterProjection records an L3 projection declaration (record-only). It
// is the single source of truth a cell uses to declare a projection; cellgen
// derives it from slice.yaml contractUsages into cell_gen.go. Hand-written
// RegisterProjection calls in business code would diverge from that single
// source, so the call must only appear in:
//
//   - _test.go files (tests of the seam / test cells)
//   - the cellgen projection wiring file cell_gen.go ONLY (basename == cell_gen.go
//     AND the "gocell generate cell" DO-NOT-EDIT banner). Sibling generated files
//     (healthz_gen.go / slice_gen.go) carry the IDENTICAL banner but are NOT
//     sanctioned RegisterProjection callsites (basename pins the producer, marker
//     pins it as generated — defense in depth, same shape as the former
//     apply-hook F6 distinction which now lives here).
//
// Status: load-bearing. The first production callsite now exists —
// examples/todoorder/cells/ordercell/cell_gen.go emits the cellgen-derived
// reg.RegisterProjection for the orderprojection harness (#834). The allowlist
// confines that (and every future) RegisterProjection call to cell_gen.go; a
// hand-written call elsewhere in business code fails the rule.
//
// # AI-robust grading (Funnel 双向锁评级)
//
//   - Downstream: Medium archtest caller allowlist. Go cannot type-gate who
//     calls a public method, so the archtest is the strongest achievable form.
//   - Upstream: Medium — permanently (won't-do, gh #1372). A "cellgen-only sealed
//     token argument" is NOT expressible in Go: cellgen emits RegisterProjection
//     into the cell's OWN package (cell_gen.go sits beside the hand-written
//     cell.go), and Go has no compile-time identity for "generated code". Any
//     token constructor the generated file can call, a hand-written sibling in the
//     same package can call too. Same permanent Go-language ceiling as Subscribe /
//     RegisterWebhookReceiver and the holder-seal family #851 / #893 / #1282.
//
// This is the upstream complement of PROJECTION-APPLY-HOOK-FUNNEL-01: cellgen's
// single source is reg.RegisterProjection (guarded here); the Coordinator.Subscribe
// terminal that consumes it lives in the bootstrap drain (guarded there). Raw
// framework infrastructure never reaches cell code — that seal is Hard (type
// system); these two caller allowlists are the Medium complements.
//
// # Blind spots
//
//   - B1. Function-value indirection (`f := reg.RegisterProjection; f(req)`):
//     the CallExpr Fun is an *ast.Ident → *types.Var, invisible to
//     ResolveMethodCall. Covered by
//     TestProjectionRegisterFunnel01_ReverseBlindSpot_NoFuncValue.
//
// ref: tools/archtest/projection_apply_hook_funnel_test.go (sibling terminal funnel)
// ref: docs/architecture/202605261620-adr-cqrs-projection-lifecycle-harness.md §7
