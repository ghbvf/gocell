package archtest

// INVARIANT: ARCHTEST-MODULE-PATH-FUNNEL-01
//
// module_path_funnel_test.go — the migration-convergence ratchet for M3
// (docs/architecture/202605281200-adr-cell-development-external-repo.md §R1/M3).
//
// Goal: make every archtest rule module-path-agnostic so an external Cell repo
// can run it against its own module. A rule's reference to a GoCell PLATFORM
// symbol path must be derived from the single sanctioned const
// [PlatformModulePath] (external.go) — NOT a bare "github.com/ghbvf/gocell…"
// string literal — so (a) a module rename updates exactly one place and (b)
// "no rule hardcodes the platform path" becomes machine-checkable.
//
// # Two detectors
//
//	1. BARE LITERAL (AST, build-tag-agnostic): firstBarePlatformLiteralLine scans
//	   every tools/archtest file (DirsScope, IncludeTests) for a STRING literal
//	   whose value is, or is a child of, PlatformModulePath. Offenders are gated
//	   by a FROZEN BASELINE (testdata/module_path_funnel.baseline) — see below.
//	2. RECONSTRUCTION (typed const-eval, #1304): collectPlatformReconstructions
//	   loads the top-level ./tools/archtest package (Typed, Tests:true) and folds
//	   every `+` BinaryExpr via go/types constant folding (EvaluateConstString).
//	   A chain that folds to a bare platform value is a HARD violation (never
//	   baselined — reconstruction is obfuscation, not legacy backlog), UNLESS its
//	   provenance reaches the sanctioned PlatformModulePath const — directly
//	   (PlatformModulePath+"/x") or transitively through same-package derived
//	   consts (const p = PlatformModulePath+"/a"; const q = p+"/b") — in which
//	   case it is exempt.
//
// # Frozen baseline (bare-literal ratchet)
//
// The baseline records the CURRENT set of files that still contain a bare
// platform-path literal (the migration backlog) and asserts two directions:
//
//   - A NEW file introducing a bare literal → not in baseline → CI red
//     (regression: a new rule hardcoded the path instead of using PlatformModulePath).
//   - A migrated file (literal removed) still listed in baseline → CI red,
//     forcing the author to delete it from the baseline (the ratchet-down step).
//
// Unlike a golden, the baseline is NEVER regenerated by -update — it is a
// monotone ceiling (ArchUnit's FreezingArchRule / ViolationStore pattern:
// fail-on-new, no auto-grow). ref: TNG/ArchUnit freeze/FreezingArchRule.java.
//
// MIGRATION TERMINAL STATE REACHED (#1302 complete, #1304): the baseline is now
// EMPTY. Direction 1 fails ANY offender (none is baselined); Direction 2 has no
// entries. The funnel therefore operates as a PURE BAN — no exception escape, no
// -update launder path. This is the strongest UPSTREAM form the rule's shape can
// reach; see the AI-robust rating for why it is still Medium (not Hard).
//
// # AI-robust rating (funnel double-lock — two honest axes)
//
//   - DOWNSTREAM Hard (detection robustness). The typed reconstruction detector
//     closes the realistic evasion vectors via go/types constant folding +
//     object-identity exemption (alias-proof, same-value-forge-proof):
//       · bare literal / literal-fragment `+` chain  — folded & flagged;
//       · const-of-const fragment chain (residual a)  — folded & flagged (#1304);
//       · cross-package const fragment    (residual b) — folded & flagged (#1304);
//       · sanctioned PlatformModulePath+"/x" + derived consts (q = p+"/b" where
//         p = PlatformModulePath+"/a") — exempt by PROVENANCE: a leaf operand
//         resolves (info.Uses → *types.Const) to PlatformModulePath, traced
//         transitively through same-package const RHS. Matched by const object
//         identity (name + declaring package path), NOT by string value, so a
//         same-VALUE forgery in another package, or a cross-package fragment
//         whose RHS is not visible here, is still flagged.
//     RESIDUAL (c), PERMANENT CEILING — honestly stated, NOT Hard: a path
//     reconstructed via RUNTIME string ops (strings.Join / fmt.Sprintf / []byte)
//     is not a compile-time constant, so go/types cannot fold it and the detector
//     cannot reach it. Closing it needs SSA/dataflow, beyond archtest's ceiling;
//     such deliberate obfuscation would not survive review. This is a permanent
//     won't-do (no upgrade issue), same family as #851 / #893 / #1282 / #1424.
//
//   - UPSTREAM Medium (NOT Hard) — permanent Go ceiling. Go cannot make "an
//     author writes a bare platform literal in arbitrary source" inexpressible:
//     the ban is enforced at CI test time (an archtest), not at compile time. The
//     empty baseline removes the exception escape (the strongest achievable
//     upstream form), but the axis stays Medium — type-system Hard is unreachable
//     for a "do not write this string value" rule. Do NOT relabel the empty-
//     baseline pure ban as "Hard" (the pre-#1304 godoc did; corrected here).
//
// # Blind spots (declared) + reverse self-checks
//
//	(a) const-of-const fragment reconstruction — COVERED (#1304) by the typed
//	    detector. RED self-check: modulepathfunnelfixture/red_const_of_const.go.
//	(b) cross-package const fragment reconstruction — COVERED (#1304). RED
//	    self-check: modulepathfunnelfixture/red_cross_pkg.go.
//	(c) runtime string ops (strings.Join / fmt.Sprintf / []byte) — NOT covered;
//	    permanent ceiling (see DOWNSTREAM residual above). GREEN self-check:
//	    modulepathfunnelfixture/green_runtime_ops.go asserts it is NOT flagged,
//	    documenting the honest boundary (not a vacuity miss).
//	(d) build-tagged rule files — the typed reconstruction scan runs under the
//	    DEFAULT build config. The only build-tagged files in package archtest are
//	    two //go:build !windows rule files, which DO compile under the default
//	    config on the Linux/macOS CI where archtest runs, so they are covered.
//	    archtest_fixture-tagged files are test scaffolding (not rules) and are
//	    excluded; the bare-literal firstBare scan still covers them AST-wise,
//	    build-tag-agnostically. No FlatNonDefaultTags() double-scan is needed
//	    (no tagged rule file would be missed).
//	    The sanctioned-exemption is additionally exercised by the MAIN scan: 369
//	    real PlatformModulePath+"/…" derivations live in funnel scope (real-source
//	    AST capture); the main rule staying green proves all are exempted.

