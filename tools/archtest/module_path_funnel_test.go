const barePlatformLiteralMsg = "bare \"" + PlatformModulePath +
	"\" string literal — derive platform symbol paths from PlatformModulePath " +
	"(see external.go / ARCHTEST-MODULE-PATH-FUNNEL-01)"

// platformReconstructionMsg is the diagnostic for a `+` chain that go/types folds
// to a bare platform value without a sanctioned PlatformModulePath operand.
const platformReconstructionMsg = "platform module path reconstructed from " +
	"const fragments (const-of-const / cross-package const) — derive it from " +
	"PlatformModulePath (see external.go / ARCHTEST-MODULE-PATH-FUNNEL-01)"

// modulePathFunnelSanctioned is the one file permitted to contain the bare
// platform-path literal: external.go, which declares PlatformModulePath.
const modulePathFunnelSanctioned = "tools/archtest/external.go"

// platformModulePathConstName is the identifier the reconstruction exemption
// recognizes as the sanctioned platform-path source.
const platformModulePathConstName = "PlatformModulePath"

// platformModulePathDeclPkgPath is the import path of the package that DECLARES
// PlatformModulePath (external.go, package archtest). It is DERIVED from the
// sanctioned const itself — never a bare literal — so it is itself exempt when
// the rule scans its own file, keeping the exemption self-consistent.
const platformModulePathDeclPkgPath = PlatformModulePath + "/tools/archtest"

// TestArchtestModulePathFunnel enforces ARCHTEST-MODULE-PATH-FUNNEL-01. The bare-
// literal detector (firstBarePlatformLiteralLine) gates offenders by the frozen
// baseline (now empty = pure ban). The typed reconstruction sub-check
// (no-reconstruction) closes the const-of-const / cross-package residual.
func TestArchtestModulePathFunnel(t *testing.T) {
	t.Parallel()
	root := findModuleRoot(t)
	// IncludeTests: today's rule logic lives in *_test.go; the funnel must see
	// it. testdata/ is skipped by DirsScope's default skip set; internal/ and
	// the sanctioned site are excluded by inFunnelScope.
	scope := DirsScope(root, []string{"tools/archtest"}, IncludeTests())

	// offenders: rel path -> first line carrying a bare platform literal.
	offenders := make(map[string]int)
	_ = Run(t, AST(scope), func(p *Pass) []Diagnostic {
		for _, f := range p.Files {
			rel := p.Rel(f)
			if !inFunnelScope(rel) {
				continue
			}
			if line, ok := firstBarePlatformLiteralLine(p.Fset, f); ok {
				offenders[rel] = line
			}
		}
		return nil
	})

	const baselineRel = "testdata/module_path_funnel.baseline"
	baseline := readModulePathBaseline(t,
		filepath.Join(root, "tools", "archtest", baselineRel))

	// Direction 1 (fail-on-new, pure ban): an offender absent from the frozen
	// baseline is a NEW regression — no -update can launder it in. With the
	// baseline empty (#1302 terminal state), this fails ANY bare literal.
	for rel, line := range offenders {
		if !baseline[rel] {
			t.Errorf("ARCHTEST-MODULE-PATH-FUNNEL-01: %s:%d: %s\n"+
				"(NEW bare literal — not in the frozen %s; derive it from "+
				"PlatformModulePath, do not hand-add it to the baseline)",
				rel, line, barePlatformLiteralMsg, baselineRel)
		}
	}
	// Direction 2 (ratchet-down): a baseline file that no longer offends must be
	// deleted from the baseline, so the ceiling only shrinks.
	for rel := range baseline {
		if _, still := offenders[rel]; !still {
			t.Errorf("ARCHTEST-MODULE-PATH-FUNNEL-01: %s no longer contains a bare platform "+
				"literal — delete it from %s (ratchet-down)", rel, baselineRel)
		}
	}

	// Typed reconstruction sub-check: closes the declared residual (a)
	// const-of-const and (b) cross-package const via go/types constant folding,
	// with an object-identity exemption for the sanctioned PlatformModulePath
	// operand. Loads only the top-level ./tools/archtest package (rule files);
	// the internal/ fixture packages and archtest_fixture scaffolding are not in
	// this package, so they are not scanned here (the RED fixtures are exercised
	// by TestModulePathFunnel_TypedReconstruction instead).
	t.Run("no-reconstruction", func(t *testing.T) {
		t.Parallel()
		sawTestFile := false
		diags := Run(t, Typed(TypedOpts{Tests: true}, []string{"./tools/archtest"}),
			func(p *Pass) []Diagnostic {
				if p.Pkg == nil || p.TypesInfo == nil {
					return nil
				}
				for _, f := range p.Files {
					if strings.HasSuffix(p.Rel(f), "_test.go") {
						sawTestFile = true
					}
				}
				return collectPlatformReconstructions(p, func(rel string) bool {
					return !inFunnelScope(rel)
				})
			})
		require.True(t, sawTestFile,
			"ARCHTEST-MODULE-PATH-FUNNEL-01 no-reconstruction scope regression: "+
				"Tests:true must surface *_test.go (rule files are archtest test "+
				"files); a Tests:false scope would make the reconstruction check "+
				"vacuously green — see function godoc.")
		Report(t, "ARCHTEST-MODULE-PATH-FUNNEL-01", diags)
	})
}

// collectPlatformReconstructions folds every `+` BinaryExpr in p (a typed Pass)
// via go/types constant folding and flags those that reconstruct a bare platform
// value WITHOUT a sanctioned PlatformModulePath operand. skip(rel) excludes files
// from the scan (nil = scan all). Runtime string ops (strings.Join etc.) are not
// constants, so EvaluateConstString returns false and they are out of reach — the
// permanent residual (c).
func collectPlatformReconstructions(p *Pass, skip func(rel string) bool) []Diagnostic {
	if p.Pkg == nil || p.TypesInfo == nil {
		return nil
	}
	constRHS := buildPackageConstRHS(p)
	var diags []Diagnostic
	for _, f := range p.Files {
		rel := p.Rel(f)
		if skip != nil && skip(rel) {
			continue
		}
		EachInSubtree[ast.BinaryExpr](f, func(be *ast.BinaryExpr) {
			if be.Op != token.ADD {
				return
			}
			v, ok := EvaluateConstString(p.TypesInfo, be)
			if !ok || !isBarePlatformValue(v) {
				return
			}
			if hasSanctionedPlatformOperand(p.TypesInfo, be, constRHS, map[*types.Const]bool{}) {
				return
			}
			diags = append(diags, diagAt(rel, p.Fset.Position(be.Pos()).Line,
				platformReconstructionMsg))
		})
	}
	return diags
}

// buildPackageConstRHS maps every same-package const object to the AST of its
// declared value, so [hasSanctionedPlatformOperand] can trace provenance through
// derived consts (const x = PlatformModulePath + "/a"; const y = x + "/b").
// Grouped/iota consts without an explicit value at their index are skipped.
// Cross-package consts are absent from the map (their RHS is in another package's
// files), which is exactly why a cross-package fragment stays a violation.
func buildPackageConstRHS(p *Pass) map[*types.Const]ast.Expr {
	m := make(map[*types.Const]ast.Expr)
	for _, f := range p.Files {
		EachInSubtree[ast.GenDecl](f, func(gd *ast.GenDecl) {
			if gd.Tok != token.CONST {
				return
			}
			EachInChildren[ast.ValueSpec](gd, func(vs *ast.ValueSpec) {
				for i, name := range vs.Names {
					if i >= len(vs.Values) {
						continue
					}
					if c, ok := p.TypesInfo.Defs[name].(*types.Const); ok {
						m[c] = vs.Values[i]
					}
				}
			})
		})
	}
	return m
}

// hasSanctionedPlatformOperand reports whether expr's provenance reaches the
// sanctioned PlatformModulePath const. A `+` chain whose value derives —
// directly or transitively through same-package derived consts — from
// PlatformModulePath is a sanctioned derivation and is exempt, even though it
// folds to a platform-prefixed value. A reconstruction from fragments that never
// touch PlatformModulePath (literal fragments, an unrelated const-of-const, or a
// cross-package const whose RHS is not visible here) is NOT exempt. visited
// guards against pathological cycles (illegal in Go, but cheap insurance).
func hasSanctionedPlatformOperand(info *types.Info, expr ast.Expr,
	constRHS map[*types.Const]ast.Expr, visited map[*types.Const]bool,
) bool {
	switch e := expr.(type) {
	case *ast.ParenExpr:
		return hasSanctionedPlatformOperand(info, e.X, constRHS, visited)
	case *ast.BinaryExpr:
		return hasSanctionedPlatformOperand(info, e.X, constRHS, visited) ||
			hasSanctionedPlatformOperand(info, e.Y, constRHS, visited)
	case *ast.Ident:
		return constOperandSanctioned(info, info.Uses[e], constRHS, visited)
	case *ast.SelectorExpr:
		return constOperandSanctioned(info, info.Uses[e.Sel], constRHS, visited)
	}
	return false
}

// constOperandSanctioned reports whether the const obj is — or transitively
// (through its same-package RHS) derives from — the sanctioned PlatformModulePath
// const. A const whose RHS is not visible here (cross-package, or no explicit
// value) terminates the trace as NOT sanctioned.
func constOperandSanctioned(info *types.Info, obj types.Object,
	constRHS map[*types.Const]ast.Expr, visited map[*types.Const]bool,
) bool {
	c, ok := obj.(*types.Const)
	if !ok || c.Pkg() == nil {
		return false
	}
	if isPlatformModulePathConst(c) {
		return true
	}
	if visited[c] {
		return false
	}
	rhs, ok := constRHS[c]
	if !ok {
		return false
	}
	visited[c] = true
	return hasSanctionedPlatformOperand(info, rhs, constRHS, visited)
}

// isPlatformModulePathConst reports whether obj is THE sanctioned
// PlatformModulePath const — matched by NAME + declaring PACKAGE PATH (object
// identity), not by string value. A same-value const declared elsewhere has a
// different package path and is therefore NOT exempt (forge-proof); an import
// alias resolves to the same object and is therefore still exempt (alias-proof).
func isPlatformModulePathConst(obj types.Object) bool {
	c, ok := obj.(*types.Const)
	if !ok || c.Pkg() == nil {
		return false
	}
	return c.Name() == platformModulePathConstName &&
		c.Pkg().Path() == platformModulePathDeclPkgPath
}

// inFunnelScope reports whether a repo-relative path is within the funnel's scan
// scope: under tools/archtest/, but not the internal/ loader primitives, not
// testdata/, and not the sanctioned PlatformModulePath declaration site.
func inFunnelScope(rel string) bool {
	return strings.HasPrefix(rel, "tools/archtest/") &&
		!strings.HasPrefix(rel, "tools/archtest/internal/") &&
		!strings.Contains(rel, "/testdata/") &&
		rel != modulePathFunnelSanctioned
}

// readModulePathBaseline reads the frozen migration baseline: one repo-relative
// path per line, blank lines and `#` comments ignored. A missing file fails loud
// (the baseline is a required, checked-in artifact).
func readModulePathBaseline(t *testing.T, path string) map[string]bool {
	t.Helper()
	data, err := os.ReadFile(path) //nolint:gosec // test-derived path under module root
	if err != nil {
		t.Fatalf("ARCHTEST-MODULE-PATH-FUNNEL-01: read baseline %s: %v", path, err)
	}
	out := make(map[string]bool)
	for _, ln := range strings.Split(string(data), "\n") {
		ln = strings.TrimSpace(ln)
		if ln == "" || strings.HasPrefix(ln, "#") {
			continue
		}
		out[ln] = true
	}
	return out
}

// firstBarePlatformLiteralLine returns the source line of the first STRING
// literal in f (excluding import-spec paths) whose unquoted value is, or is a
// child path of, PlatformModulePath, and whether any was found. Import-spec
// paths are excluded because importing a GoCell package is normal Go, not the
// hardcoding this funnel targets; the sanctioned PlatformModulePath+"/x" form is
// invisible because its fragment literal is "/x" (no platform prefix).
func firstBarePlatformLiteralLine(fset *token.FileSet, f *ast.File) (int, bool) {
	importLits := make(map[*ast.BasicLit]bool, len(f.Imports))
	for _, imp := range f.Imports {
		if imp.Path != nil {
			importLits[imp.Path] = true
		}
	}
	lit, found := FindFirstInSubtree[ast.BasicLit](f, func(lit *ast.BasicLit) bool {
		if lit.Kind != token.STRING || importLits[lit] {
			return false
		}
		val, err := strconv.Unquote(lit.Value)
		if err != nil {
			return false
		}
		return isBarePlatformValue(val)
	})
	if !found {
		return 0, false
	}
	return fset.Position(lit.Pos()).Line, true
}

// isBarePlatformValue reports whether v is the platform module path itself or a
// child path of it — i.e. a value that directly hardcodes the platform path.
// Genuine FRAGMENTS (e.g. "github.com/ghbvf/", which is a prefix of, not prefixed
// by, the path) are NOT bare values and are the reconstruction detector's domain.
func isBarePlatformValue(v string) bool {
	return v == PlatformModulePath || strings.HasPrefix(v, PlatformModulePath+"/")
}

// TestModulePathFunnel_TypedReconstruction is the RED/GREEN reverse self-check for
// the typed reconstruction detector (#1304). It loads the fixture package
// (modulepathfunnelfixture, build tag archtest_fixture) and asserts which FILES
// collectPlatformReconstructions flags: the two typed-only reconstructions (a)/(b)
// MUST be flagged; the sanctioned derivation, the unrelated concat, and the
// runtime-ops residual (c) MUST NOT be flagged.
func TestModulePathFunnel_TypedReconstruction(t *testing.T) {
	t.Parallel()
	const fixturePattern = "./tools/archtest/internal/modulepathfunnelfixture/..."
	var diags []Diagnostic
	_ = Run(t, Fixture(FixtureOpts{Tests: false}, []string{fixturePattern}),
		func(p *Pass) []Diagnostic {
			diags = append(diags, collectPlatformReconstructions(p, nil)...)
			return nil
		})

	flagged := make(map[string]bool)
	for _, d := range diags {
		flagged[filepath.Base(d.Rel)] = true
	}

	// RED — typed-only reconstructions MUST be flagged (anti-vacuity).
	require.True(t, flagged["red_const_of_const.go"],
		"residual (a) const-of-const reconstruction must be flagged by the typed detector")
	require.True(t, flagged["red_cross_pkg.go"],
		"residual (b) cross-package const reconstruction must be flagged by the typed detector")
	// GREEN — exemption + negative controls MUST NOT be flagged.
	require.False(t, flagged["green_sanctioned.go"],
		"sanctioned PlatformModulePath derivation must be exempt (object identity)")
	require.False(t, flagged["green_unrelated.go"],
		"non-platform concat must not be flagged")
	require.False(t, flagged["green_runtime_ops.go"],
		"runtime string ops are the permanent residual (c) — not statically foldable, by design")
}

// TestFirstBarePlatformLiteralLine_partition pins the partition between the two
// detection mechanisms, so excluding bare-value literals from the reconstruction
// detector can NEVER hide a hardcode:
//
//   - A bare-VALUE literal (or a const whose RHS is that literal) is caught HERE
//     at its literal site → it lands in offenders/baseline. So the hardcode is
//     always tracked at its literal site, never silently lost.
//   - A FRAGMENT-only reconstruction (no single operand is a bare value) is NOT
//     caught here — it is the typed reconstruction detector's domain
//     (collectPlatformReconstructions), which now covers const-of-const and
//     cross-package const (residuals (a)/(b), #1304).
//
// Together the two are exhaustive over compile-time-constant forms. The only
// uncovered form is the documented PERMANENT residual (c): runtime string ops,
// which are not constants and which neither detector can reach.
func TestFirstBarePlatformLiteralLine_partition(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name      string
		src       string
		wantFound bool
	}{
		{
			"bare-value-const-used-in-concat",
			"package p\nconst full = \"github.com/ghbvf/gocell\"\nvar _ = full + \"/x\"\n", true,
		},
		{
			"bare-literal-child-path",
			"package p\nvar _ = \"github.com/ghbvf/gocell/pkg/x\"\n", true,
		},
		{"only-fragments-no-bare", // reconstruction detector's job, not firstBare's
			"package p\nconst a = \"github.com/\"\nconst b = \"ghbvf/gocell\"\nvar _ = a + b\n", false},
		{
			"gocell-import-path-excluded",
			"package p\nimport _ \"github.com/ghbvf/gocell/pkg/errcode\"\n", false,
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			fset := token.NewFileSet()
			f, err := parser.ParseFile(fset, c.name+".go", c.src, 0)
			if err != nil {
				t.Fatalf("parse: %v", err)
			}
			if _, found := firstBarePlatformLiteralLine(fset, f); found != c.wantFound {
				t.Errorf("firstBarePlatformLiteralLine found=%v, want %v", found, c.wantFound)
			}
		})
	}
}
