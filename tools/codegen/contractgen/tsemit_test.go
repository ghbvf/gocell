// TestRenderBarrel verifies the barrel index.ts output.
func TestRenderBarrel(t *testing.T) {
	t.Parallel()
	entries := []tsBarrelEntry{
		{Alias: "httpOrderCreateV1", ImportPath: "./contracts/http/order/create/v1/types"},
		{Alias: "eventOrderCreatedV1", ImportPath: "./contracts/event/order-created/v1/types"},
	}
	got, err := renderBarrel(entries)
	if err != nil {
		t.Fatalf("renderBarrel: %v", err)
	}
	out := string(got)

	// Must have header
	if !strings.HasPrefix(out, "// Code generated by gocell generate") {
		t.Errorf("missing generated header; got:\n%s", out[:min(200, len(out))])
	}
	// Must have re-exports
	if !strings.Contains(out, "export * as httpOrderCreateV1 from") {
		t.Errorf("missing httpOrderCreateV1 export; got:\n%s", out)
	}
	if !strings.Contains(out, "export * as eventOrderCreatedV1 from") {
		t.Errorf("missing eventOrderCreatedV1 export; got:\n%s", out)
	}
}

// min returns the smaller of two ints.
func min(a, b int) int {
	if a < b {
		return a
	}
	return b
}
