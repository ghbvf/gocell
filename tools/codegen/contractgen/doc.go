// Package contractgen renders typed Go scaffolding from a single contract.yaml +
// its referenced JSON schemas. It is the codegen pass behind
// `gocell generate contract`.
//
// # Pipeline
//
// buildContractSpec parses the contract metadata + schemaRefs into a
// *ContractGenSpec (spec.go); the spec is then handed to one or more
// templates registered in templates/ via render.go. Each output file lives
// under generated/contracts/<segments>/ where the segments mirror the
// dot-separated contract id (with every "internal" segment rewritten to
// "internalapi" to keep the generated package importable from cells/ and
// examples/ — Go's internal package rule otherwise blocks cross-tree imports;
// see pkg/contractpath).
//
// # Artifact matrix
//
// The generator emits a fixed set of files per contract kind. The authoritative
// matrix is contractArtifacts in generator.go (the single source consumed by
// both generateOneContract and RenderContractArtifacts); this table mirrors it.
// Every file carries the "Code generated by gocell generate contract. DO NOT
// EDIT." header so editors and lint suites recognize them as derived artifacts.
//
// Columns are file stems; each emitted file is <stem>_gen.go.
//
//	           | types | iface | handler | client | spec | subscription | projection | saga | command
//	-----------+-------+-------+---------+--------+------+--------------+------------+------+---------
//	http       |   ✔   |   ✔   |    ✔    |  ✔ **  |   —  |      —       |     —      |   —  |    —
//	event      |   ✔   |   ✔   |    —    |   —    |   ✔  |      ✔       |     ✔      |   —  |    —
//	command    |   ✔   |   —   |    —    |   —    |   —  |      —       |     —      |   —  |    ✔
//	projection |   ✔   |   ✔   |    —    |   —    |   —  |      —       |     —      |   —  |    —
//	grpc       |   —   |   —   |    —    |   —    |   —  |      —       |     —      |   —  |    —
//	saga       |   ✔   |  ✔ *  |    —    |   —    |   —  |      —       |     —      |   ✔  |    —
//	webhook    |   —   |   —   |    —    |   —    |   —  |      —       |     —      |   —  |    —
//
// * saga's iface_gen.go is an empty package clause (no Service interface); the
// typed business interface is Impl in saga_gen.go. See the iface_gen.go section.
//
// ** client_gen.go is the only PER-CONTRACT-gated http artifact (#2093): it is
// emitted only when shouldEmitClient is true — i.e. an internal-path contract that
// declares endpoints.clients (the sibling-cell caller allowlist). Public http
// contracts and internal contracts without a clients allowlist get no client.
// See the client_gen.go section and generator.go shouldEmitClient.
//
// webhook and grpc emit no contractgen artifacts at all: webhook registration
// derives via cellgen from slice.yaml; grpc's server contract is buf's generated
// pb.<Svc>Server interface, so contractgen emits no Go for kind=grpc (#1688).
//
// # types_gen.go (all kinds except webhook and grpc)
//
// Renders Request / Response / Payload / Headers DTOs from the schemaRefs.
// For HTTP contracts, additionally renders the typed-response-envelope set:
// one {HandlerMethod}ResponseObject interface plus N concrete typed structs,
// one per status declared in contract.yaml http.responses[] union with
// http.successStatus. The generator's Responses IR slice is the single source
// of truth — CH-06 governance enforces the contract.yaml ↔ types_gen.go
// bijection (see kernel/governance/rules_http.go).
//
// Naming convention for typed response structs:
//
//	{HandlerMethod}{Status}JSONResponse        — success body-bearing (200/201/etc.)
//	{HandlerMethod}{Status}NoContentResponse   — success 204 marker (empty struct)
//	{HandlerMethod}{Status}ErrorResponse       — declared 4xx/5xx, Body errcode.Error
//
// Each typed struct implements an unexported visit{HandlerMethod}Response
// method, closing the implementation set to types declared in this package.
// Service code constructs one of these structs to return; the generated
// handler dispatches via the Visit method, which writes the pinned status +
// body (errors go through pkg/httputil.WriteErrorWithStatus to share the 4xx/
// 5xx redaction policy with the framework fallback path).
//
// # iface_gen.go (http/event/projection/saga — not command/grpc/webhook)
//
// Renders the Service interface that the cell-side handler must implement.
// For HTTP contracts the signature is
// `Method(ctx, *Request) ({HandlerMethod}ResponseObject, error)`: the typed
// response carries declared 2xx/4xx/5xx outcomes; the Go error return is
// reserved for un-declared framework 5xx (panic recover, infrastructure
// faults), in which case the generated handler falls back to
// pkg/httputil.WriteError(err) and derives the response status from
// errcode.Kind. For event contracts the signature is
// `Handle{Topic}(ctx, *Payload) error`. For
// kind=saga, iface_gen.go is intentionally empty (just the package clause) —
// the typed business interface is the Impl interface emitted in saga_gen.go,
// not a Service here. command contracts emit no iface_gen.go — the typed Handler
// interface lives in command_gen.go (a Service interface there would collide);
// grpc and webhook contracts emit no contractgen package at all: grpc's server
// contract is buf's generated pb.<Svc>Server interface (proto-derived, declares
// every RPC, carries the forward-compat mustEmbedUnimplemented marker), so a
// parallel contractgen interface would be a register-incompatible,
// package-colliding duplicate (#1688); webhook registration derives via cellgen
// from slice.yaml.
//
// # handler_gen.go (kind=http only)
//
// Renders the http.Handler that decodes the request, dispatches to Service,
// and writes the typed response. Wires auth.Mount with the contract's
// auth.Public / auth.Bootstrap / auth.PasswordResetExempt flags as declared
// in contract.yaml. Pagination endpoints — every GET that declares cursor +
// limit, regardless of additional path or filter query params — route through
// pkg/httputil.ParsePageParams so the limit error envelope is uniform across
// the entire HTTP surface; this is byte-pinned by the http_order_list_v1
// handler_gen.go golden in render_test.go — any reintroduction of inline
// strconv.ParseInt("limit") in the template diffs the golden output.
// (funnel-first; see docs/plans/202605070431-pr403-funnel-fix-roadmap.md §7.)
//
// # client_gen.go (kind=http, gated by shouldEmitClient — #2093)
//
// Renders the cross-cell contract Client (unexported fields → not externally
// struct-literal constructable). It is the sole *generated* sibling-cell caller
// type; its Hard property is codegen + byte golden (the generated artifact is
// frozen), NOT a sealed interface — transport.CellTransport is a plain exported
// interface, so holding one is not a type-level seal, and "the constructor only
// takes a CellTransport" merely means a bare *http.Client is not accepted by that
// signature (a cell could still hold net/http; that bypass is caught by the Medium
// backstops below, not the compiler). One NewClientFor<Cell> is emitted per
// endpoints.clients cell, baking the caller-cell identity as a literal so a
// wrong/forged callerCell is unexpressible (F2). The method encodes path + query
// (url.Values → RawQuery set BEFORE signing, since SignInternalRequest folds
// RawQuery into the MAC — F3) + body, signs with a service token
// (auth.SignInternalRequest), dispatches via DoContract, and on the declared
// success status decodes the body — into the directly-unmarshalable Response, or
// for responseProjection contracts (whose Response.Data is the sealed
// projection.ResourceProjection) into the resource-item DTO via the {data: ...}
// envelope (Endpoint.ClientDecodeDTO/List). Domain error mapping is the caller's
// job: the method returns (decoded, httpStatus, err) and returns (nil, status, nil)
// for a non-success status. Emitted ONLY when shouldEmitClient is true (internal
// path + endpoints.clients declared) and only for shapes the client can faithfully
// encode (validateGeneratedClientEncodable rejects NoContent / custom non-tenant
// headers at codegen — F3/F4). The Medium caller-side backstops that a cell reaches
// siblings ONLY through this client are CELL-TRANSPORT-DOCONTRACT-CALLER-01 +
// CELL-SYNC-TRANSPORT-FUNNEL-01.
//
// # spec_gen.go (kind=event only)
//
// Renders the cell-facing contractspec.ContractSpec literal so cells can
// reference one canonical declaration for the topic, transport, delivery
// semantics, and idempotency policy. Single source for the contract id
// stamped into every consumer's reg.Subscribe call.
//
// # subscription_gen.go (kind=event only)
//
// Renders the typed Subscription registration helper. Cells call
// `{Topic}.Subscribe(reg, handler, consumerGroup)`; the helper resolves the
// canonical ContractSpec from spec_gen.go and asserts the consumerGroup is
// a non-empty string at registration time.
//
// # projection_gen.go (kind=event only)
//
// Renders the NewProjectionRequest mount-helper. cellgen is the only production
// caller (via reg.RegisterProjection, funnel-locked by PROJECTION-REGISTER-FUNNEL-01).
// The function references the package-private spec var so callers receive a
// fully-formed cell.ProjectionRequest without the spec value escaping as a
// bare contractspec.ContractSpec literal.
//
// # saga_gen.go (kind=saga only)
//
// Renders the typed saga scaffolding from the contract.yaml saga block:
//
//   - DefinitionID — the saga.Definition.ID const (= contract id).
//   - <Step>Output DTOs (in types_gen.go) — one per step's output schemaRef.
//   - Impl — the typed business interface. Step 0 is Run<Name>(ctx, inst); each
//     later step is Run<Name>(ctx, inst, <PrevStep>Output) (the runtime feeds
//     the previous step's output as prevState; step 0 gets nil). A step gets a
//     Compensate<Name>(ctx, inst, <Step>Output) method only when it declares
//     compensate (default true).
//   - BuildDefinition(impl) *saga.Definition — wraps the typed methods into the
//     untyped saga.StepFunc / saga.CompensateFunc via JSON (un)marshal.
//   - Register(impl) (*saga.InMemoryRegistry, error) — single-saga convenience;
//     for multi-saga registries call BuildDefinition and compose via
//     saga.NewInMemoryRegistry.
//
// # Cell attribution constraint
//
// Generated *Handler MUST be mounted from a cell-owned RouteGroup
// (typically via the cellgen-generated cell_gen.go reg.RouteGroup wiring).
// http_requests_total `cell` label depends on this:
//
//   - Mounted via reg.RouteGroup → CellAttribution middleware injects
//     kernel/ctxkeys.CellID = <cellID>; metrics labeled cell=<cellID>.
//   - Mounted standalone (e.g. http.Handle) → no CellID context, metrics
//     fall back to the "_runtime" sentinel — silent observability bug.
//
// Reference: .claude/rules/gocell/observability.md "HTTP Metrics `cell` Label".
//
// # Workflow: adding a new declared status code
//
//  1. Edit contracts/<path>/contract.yaml — add the new status code under
//     endpoints.http.responses[] with a schemaRef pointing to the JSON schema
//     for that status's response body (or use the shared error envelope ref for
//     4xx/5xx declared error responses).
//
// 2. Regenerate all typed structs:
//
//		go run ./cmd/gocell generate contract --all
//
//	   This reruns types.tmpl for every HTTP contract, emitting one new
//	   {HandlerMethod}{Status}JSONResponse / NoContentResponse / ErrorResponse
//	   struct for the added status, and updating the {HandlerMethod}ResponseObject
//	   interface to include it.
//
// 3. Validate governance:
//
//		go run ./cmd/gocell check contract-health   # CH-04 + CH-06 must pass
//		golangci-lint run ./...                      # 0 issues
//
//	   CH-06 (rules_http.go) verifies that the generated struct
//	   set exactly matches contract.yaml SuccessStatus ∪ responses[]; CH-04
//	   (rules_http.go) verifies the handler-emitted status set
//	   is a subset of the declared set. Both must be green before committing.
//
