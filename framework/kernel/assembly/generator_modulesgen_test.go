// TestGenerateModulesGen_CompositionForm covers the composition.CellModule
// codegen branch (Build.CompositionAPI = true), which corebundle uses. Unlike
// the legacy form (local *Module struct literals), this branch emits aliased
// imports into cellmodules/<cellID> and Module() call expressions through
// runtime/composition.CellModule. The import alias and path both carry the
// cellmodules/ segment (the composition-root layer), and module calls preserve
// assembly cell order for deterministic output (the order is NOT
// runtime-significant — the former auditcore→accesscore BootstrapLedgerStore
// handoff was removed in #1423; cross-cell wiring is now event-driven).
func TestGenerateModulesGen_CompositionForm(t *testing.T) {
	project := buildModulesTestProject()
	asm := project.Assemblies["corebundle"]
	asm.Build.CompositionAPI = true
	// Order configcore, auditcore, accesscore to assert the call list preserves
	// assembly (not sorted) order.
	asm.Cells = []metadata.AssemblyCellRef{
		{ID: metadatatest.CellIDConfigCore},
		{ID: metadatatest.CellIDAuditCore},
		{ID: metadatatest.CellIDAccessCore},
	}
	gen := NewGenerator(project, "github.com/ghbvf/gocell", "")

	out, err := gen.GenerateModulesGen("corebundle")
	require.NoError(t, err)

	content := string(out)
	assert.Contains(t, content, "// Code generated by ")
	assert.Contains(t, content, "DO NOT EDIT")
	assert.Contains(t, content, "package main")
	// Composition form: returns []composition.CellModule, not []CellModule.
	assert.Contains(t, content, "func generatedCellModules() []composition.CellModule")
	assert.Contains(t, content, `"github.com/ghbvf/gocell/framework/runtime/composition"`)
	// Aliased imports + Module() calls live under the cellmodules/ layer.
	assert.Contains(t, content, `cellmodulesaccesscore "github.com/ghbvf/gocell/cellmodules/accesscore"`)
	assert.Contains(t, content, `cellmodulesauditcore "github.com/ghbvf/gocell/cellmodules/auditcore"`)
	assert.Contains(t, content, `cellmodulesconfigcore "github.com/ghbvf/gocell/cellmodules/configcore"`)
	assert.Contains(t, content, "cellmodulesaccesscore.Module()")
	assert.Contains(t, content, "cellmodulesauditcore.Module()")
	assert.Contains(t, content, "cellmodulesconfigcore.Module()")
	// No legacy local-struct form.
	assert.NotContains(t, content, "AccessCoreModule{}")
	// Zero-capability composition form: the runtime/capability import and the
	// generatedCapabilities() block must both be omitted. The import is gated on
	// the same {{if .Capabilities}} as the function; emitting it unconditionally
	// (the pre-fix template bug) would produce an unused import that fails to
	// compile for any compositionAPI assembly whose cells require nothing.
	assert.NotContains(t, content, "runtime/capability")
	assert.NotContains(t, content, "generatedCapabilities")
	// Module calls preserve assembly cell order (configcore, auditcore, accesscore).
	posConfig := indexOfStr(content, "cellmodulesconfigcore.Module()")
	posAudit := indexOfStr(content, "cellmodulesauditcore.Module()")
	posAccess := indexOfStr(content, "cellmodulesaccesscore.Module()")
	assert.Less(t, posConfig, posAudit, "configcore.Module() must precede auditcore.Module()")
	assert.Less(t, posAudit, posAccess, "auditcore.Module() must precede accesscore.Module()")
}

