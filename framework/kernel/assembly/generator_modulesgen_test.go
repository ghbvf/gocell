// indexOfStr returns the byte position of substr in s, or -1 if not found.
func indexOfStr(s, substr string) int {
	for i := range len(s) - len(substr) + 1 {
		if s[i:i+len(substr)] == substr {
			return i
		}
	}
	return -1
}

